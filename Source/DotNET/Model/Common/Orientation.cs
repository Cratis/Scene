namespace Cratis.Scene.Model.Common;

/// <summary>
/// The direction an element lays its children out in.
/// </summary>
public enum Orientation
{
    /// <summary>
    /// Children are laid out left to right.
    /// </summary>
    Horizontal = 0,

    /// <summary>
    /// Children are laid out top to bottom.
    /// </summary>
    Vertical = 1
}
