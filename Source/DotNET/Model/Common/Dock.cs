namespace Cratis.Scene.Model.Common;

/// <summary>
/// The edge of a dock panel a child is docked against.
/// </summary>
public enum Dock
{
    /// <summary>
    /// Docked against the left edge.
    /// </summary>
    Left = 0,

    /// <summary>
    /// Docked against the top edge.
    /// </summary>
    Top = 1,

    /// <summary>
    /// Docked against the right edge.
    /// </summary>
    Right = 2,

    /// <summary>
    /// Docked against the bottom edge.
    /// </summary>
    Bottom = 3
}
