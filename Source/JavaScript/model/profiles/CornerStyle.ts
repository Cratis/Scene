/** How rounded the corners of buttons, cards, the logo block and menu items are. */
export enum CornerStyle {
    /** Square-ish corners: 4 px. */
    Sharp = 'Sharp',

    /** The theme's own corner radius. The default. */
    Default = 'Default',

    /** Generously rounded corners: 18 px. */
    Round = 'Round',
}
