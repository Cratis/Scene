/**
 * How prominent a toolbar button is.
 */
export enum ToolbarEmphasis {
    /** The main action of the page: a solid, accented button. */
    Primary = 'primary',

    /** A regular action: an outlined button. The default. */
    Secondary = 'secondary',

    /** A minor action: a plain button without a frame. */
    Quiet = 'quiet',
}
