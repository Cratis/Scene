// Registered, yet the server cannot read an element of that type back: the derived type converter treats a type that has
// subclasses as a base to choose among, so it no longer accepts the type itself (PrimeReact.ConfirmDialog derives from Dialog).
export const unreadablePrototypeTypes: readonly string[] = ['PrimeReact.Dialog'];

// The prototype element types the server can read back when a screen is saved. An element saved under any other type makes the
// whole save fail, so the projection writes only these and stores everything else as an external component.
export const registeredPrototypeTypes: readonly string[] = registered;
export const serverPrototypeTypes: ReadonlySet<string> = new Set(registered.filter(type => !unreadablePrototypeTypes.includes(type)));
